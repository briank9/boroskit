// What: unusable input changes nothing and is reported.
- (void)testBadInput
{
    BKSlabCamera c = BKTestStored(0);
    BKSlabCamera before = c;
    BKSlabCamera degenerate = c;
    degenerate.focalPoint = degenerate.position;
    BKSlabCamera out = c;
    XCTAssertEqual(BKSlabCameraStore(&degenerate, 40, &out), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraStore(NULL, 40, &out), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraSpin(&c, 0, 0, NAN, 0, 1, 1), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraPan(&c, 0, 0, 0, 1, 1), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraYawPitch(&c, INFINITY, 0), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraMoveAlongView(&c, NAN, NULL), BKSlabCameraBadInput);
    XCTAssertEqual(BKSlabCameraSetWindowCenter(&c, 1, 1, 0, 600, 800, 600), BKSlabCameraBadInput);
    XCTAssertEqualWithAccuracy(BKSlabCameraLargestDifference(&c, &before), 0, 0);
    BKSlabCamera upAlongView = c;
    upAlongView.viewUp = BKV3d(0, 0, 1);   // parallel to the viewing direction
    XCTAssertEqual(BKSlabCameraOrthogonalizeUp(&upAlongView), BKSlabCameraBadInput);
    float m[9];
    XCTAssertFalse(BKSlabCameraCosines(&degenerate, m));
    XCTAssertEqual(BKSlabCameraRollDegrees(NULL), 0);
    XCTAssertTrue(isinf(BKSlabCameraLargestDifference(NULL, &c)));
}

