// What: the scan box is the box around the 8 corners, scaled; a tilted scan widens it.
- (void)testScanBox
{
    BKVec3d axes[3] = { BKV3d(1, 0, 0), BKV3d(0, 1, 0), BKV3d(0, 0, 1) };
    int32_t lo[3] = { 0, 0, 1 }, hi[3] = { 511, 511, 98 };
    BKSlabCameraBox box;
    XCTAssertTrue(BKSlabCameraScanBox(BKV3d(-10, -20, 5), axes, BKV3d(0.25, 0.25, 0.5), lo, hi, 2.0, &box));
    XCTAssertEqualWithAccuracy(box.min.x, -20, 1e-12);
    XCTAssertEqualWithAccuracy(box.max.x, 2 * (-10 + 511 * 0.25), 1e-12);
    XCTAssertEqualWithAccuracy(box.min.z, 2 * (5 + 0.5), 1e-12);
    XCTAssertEqualWithAccuracy(box.max.z, 2 * (5 + 98 * 0.5), 1e-12);

    double s = sqrt(0.5);
    BKVec3d tilted[3] = { BKV3d(s, s, 0), BKV3d(-s, s, 0), BKV3d(0, 0, 1) };
    int32_t lo2[3] = { 0, 0, 0 }, hi2[3] = { 10, 10, 10 };
    XCTAssertTrue(BKSlabCameraScanBox(BKV3d(0, 0, 0), tilted, BKV3d(1, 1, 1), lo2, hi2, 1.0, &box));
    XCTAssertEqualWithAccuracy(box.min.x, -10 * s, 1e-12);
    XCTAssertEqualWithAccuracy(box.max.x, 10 * s, 1e-12);
    XCTAssertEqualWithAccuracy(box.max.y, 20 * s, 1e-12);
    XCTAssertTrue(BKSlabCameraBoxContainsStrictly(&box, BKV3d(0, 1, 1)));
    XCTAssertFalse(BKSlabCameraBoxContainsStrictly(&box, BKV3d(0, 1, 0)));   // on a face
    int32_t bad[3] = { 5, 0, 0 }, badHi[3] = { 4, 1, 1 };
    XCTAssertFalse(BKSlabCameraScanBox(BKV3d(0, 0, 0), axes, BKV3d(1, 1, 1), bad, badHi, 1.0, &box));
}

